<script lang="ts">
  import { untrack } from 'svelte';
  import { fieldHelp, type Field, type Values } from '../lib/schema';
  import type { Platform } from '../lib/versions';
  import type { Issue } from '../lib/validate';
  import { formatOriginHeaderDetails, parseOriginHeaderDetails, type OriginHeaderDetail } from '../lib/generate';
  import { trailingWhitespace } from '../lib/ordinary-whitespace';
  import FieldDetails from './FieldDetails.svelte';

  interface Props {
    field: Field;
    values: Values;
    platform: Platform;
    issues: Issue[];
  }
  let { field, values = $bindable(), platform, issues }: Props = $props();

  const help = $derived(fieldHelp(field, platform));
  const initial = untrack(() => String(values[field.id] ?? ''));
  let emitted = $state(initial);
  let rows = $state<OriginHeaderDetail[]>(parseOriginHeaderDetails(initial));

  $effect(() => {
    const external = String(values[field.id] ?? '');
    if (external !== emitted) {
      rows = parseOriginHeaderDetails(external);
      emitted = external;
    }
  });

  function commit() {
    emitted = formatOriginHeaderDetails(rows.filter((row) => row.origin.trim()));
    values[field.id] = emitted;
  }

  function add() {
    rows.push({ origin: '', rewriteEnabled: true, autoGenerated: false });
  }

  function remove(index: number) {
    rows.splice(index, 1);
    commit();
  }

  function rowError(index: number): string | undefined {
    return issues.find((issue) =>
      issue.fieldId === field.id &&
      issue.rowIndex === index &&
      issue.level === 'error'
    )?.message;
  }
</script>

<fieldset class="field wide row-list-field">
  <legend class="lbl">
    {field.label}
    <FieldDetails {field} {platform} />
    <button type="button" class="small primary" onclick={add} aria-label="Add allowed origin">+ Add allowed origin</button>
  </legend>
  <div class="row-list">
    {#each rows as row, index (index)}
      {@const error = rowError(index)}
      {@const id = `f-${field.id}-${index}`}
      <div class="row-list-item origin-row-item">
        <label class="row-list-input" for={`${id}-origin`}>
          <span class="lbl">Allowed origin {index + 1}</span>
          <input id={`${id}-origin`} type="text" value={row.origin} placeholder="https://uag.example.com"
            spellcheck="false" autocomplete="off" class:bad={!!error}
            aria-invalid={error ? 'true' : undefined} aria-describedby={error ? `${id}-error` : undefined}
            onblur={() => { row.origin = trailingWhitespace(row.origin); commit(); }}
            oninput={(event) => { row.origin = event.currentTarget.value; commit(); }} />
          {#if error}<span class="err" id={`${id}-error`}>{error}</span>{/if}
        </label>
        <div class="origin-row-options">
          <label>
            <input type="checkbox" checked={row.rewriteEnabled}
              aria-label={`Rewrite allowed origin ${index + 1}`}
              onchange={(event) => { row.rewriteEnabled = event.currentTarget.checked; commit(); }} />
            Rewrite
          </label>
          <label>
            <input type="checkbox" checked={row.autoGenerated}
              aria-label={`Allowed origin ${index + 1} auto-generated`}
              onchange={(event) => { row.autoGenerated = event.currentTarget.checked; commit(); }} />
            Auto-generated
          </label>
        </div>
        <button type="button" class="small danger" onclick={() => remove(index)}
          aria-label={`Remove allowed origin ${index + 1}`}>Remove</button>
      </div>
    {:else}
      <p class="help">No allowed origins configured.</p>
    {/each}
  </div>
  {#if help}<span class="hint">{help}</span>{/if}
</fieldset>
