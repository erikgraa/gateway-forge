export type SecretMode = 'placeholder' | 'omit' | 'include';
export const SECRET_PLACEHOLDER = '<REDACTED>';

export interface Entry {
  key: string;
  jsonKey: string | false;
  value: Primitive;
  field: Field;
  secret: boolean;
}

export interface Block {
  /** INI section name. */
  section: string;
  target: Target;
  /** 1-based index for list blocks. */
  index?: number;
  entries: Entry[];
}

export interface GenerateOptions {
  secrets: SecretMode;
}

export interface OriginHeaderDetail {
  origin: string;
  rewriteEnabled: boolean;
  autoGenerated: boolean;
}

export function parseOriginHeaderDetails(raw: unknown): OriginHeaderDetail[] {
  const lines = Array.isArray(raw)
    ? raw
    : String(raw ?? '').split(/\r?\n/);
  return lines.flatMap((line) => {
    if (line && typeof line === 'object') {
      const item = line as Record<string, unknown>;
      if (!item.origin) return [];
      return [{
        origin: String(item.origin),
        rewriteEnabled: item.rewriteEnabled === true || /^true$/i.test(String(item.rewriteEnabled ?? '')),
        autoGenerated: item.autoGenerated === true || /^true$/i.test(String(item.autoGenerated ?? ''))
      }];
    }
    const parts = String(line).split('|').map((x) => x.trim());
    if (!parts[0]) return [];
    return [{
      origin: parts[0],
      rewriteEnabled: /^true$/i.test(parts[1] ?? ''),
      autoGenerated: /^true$/i.test(parts[2] ?? '')
    }];
  });
}

export function formatOriginHeaderDetails(details: OriginHeaderDetail[]): string {
  return details.map((x) => `${x.origin} | ${x.rewriteEnabled} | ${x.autoGenerated}`).join('\n');
}

const SECTION_ORDER = ['General', 'AdminUser', 'Azure', 'Nutanix', 'OpenShift', 'Horizon', 'Airwatch', 'AirwatchContentGateway', 'WebReverseProxy', 'RADIUSAuth', 'SecurIDAuth', 'CertificateAuth', 'OidcProviderSetting', 'IDPExternalMetadata1', 'OutboundProxySettings', 'SSLCert', 'SnmpSettings', 'SyslogServerSettings'];

function sectionRank(name: string): number {
  const i = SECTION_ORDER.findIndex((s) => name.startsWith(s));
  return i === -1 ? SECTION_ORDER.length : i;
}

function entryFor(f: Field, values: Values, mode: SecretMode): Entry | null {
  if (f.customOutput) return null;
  const raw = f.certificateInput ? certificateMode(values, f.id, f.certificateInput) : values[f.id];
  let normalized = f.rows ? serializeListValue([raw], f.rows.separator) : raw;
  if (f.escapeNewlines && typeof normalized === 'string') normalized = normalized.replace(/\r?\n/g, '\\n');
  if (isEmpty(normalized)) return null;
  if (f.omitDefault && isDefault(f, normalized)) return null;
  let value = normalized as Primitive;
  if (f.exportScale && (typeof value === 'number' || typeof value === 'string')) {
    const scaled = Number(value) * f.exportScale;
    if (Number.isFinite(scaled)) value = scaled;
  }
  if (f.secret) {
    if (mode === 'omit') return null;
    if (mode === 'placeholder') value = SECRET_PLACEHOLDER;
  }
  return { key: f.key, jsonKey: f.json === undefined ? f.key : f.json, value, field: f, secret: !!f.secret };
}

/** Resolve a config into ordered INI blocks, applying version/platform/visibility rules. */
export function collectBlocks(c: Config, opts: GenerateOptions = { secrets: 'placeholder' }): Block[] {
  const blocks = new Map<string, Block>();
  const get = (section: string, target: Target, index?: number): Block => {
    let b = blocks.get(section);
    if (!b) {
      b = { section, target, index, entries: [] };
      blocks.set(section, b);
    }
    return b;
  };

  for (const g of GROUPS) {
    if (g.target === 'cascade') continue;
    if (!groupEnabled(g, c)) continue;
    if (g.target === 'horizon' && c.values.horizon_enabled !== true) continue;
    if (g.target === 'airwatchContentGateway' && c.values.contentGateway_mode === 'shared') {
      const airwatch = get('Airwatch', 'airwatch');
      const enabledField: Field = {
        id: 'contentGateway_enabled',
        label: 'Enable Content Gateway',
        type: 'bool',
        key: 'contentGatewayEnabled',
        json: false
      };
      airwatch.entries.push({
        key: 'contentGatewayEnabled',
        jsonKey: false,
        value: true,
        field: enabledField,
        secret: false
      });
      const configField = g.fields.find((field) => field.id === 'contentGateway_cgConfigId');
      if (configField && !isEmpty(c.values.contentGateway_cgConfigId)) {
        airwatch.entries.push({
          key: 'cgConfigId',
          jsonKey: false,
          value: c.values.contentGateway_cgConfigId,
          field: configField,
          secret: false
        });
      }
      continue;
    }
    const entries: Entry[] = [];
    for (const f of g.fields.filter((field) => field.trustedCertIndex === undefined && field.hostEntryIndex === undefined)) {
      if (f.id === 'origin') continue;
      if (!fieldAvailable(f, c.version, c.platform, c.values)) continue;
      if (f.customOutput || f.ini === false) continue;
      const e = entryFor(f, c.values, opts.secrets);
      if (e) entries.push(g.target === 'deploy' ? { ...e, jsonKey: false } : e);
    }
    const hosts = hostEntryValues(c.values, g.fields);
    hosts.forEach((value, index) => {
      const field = g.fields.find((f) => f.hostEntryIndex === 1)!;
      entries.push({ field, key: `hostEntry${index + 1}`, jsonKey: false, value, secret: false });
    });
    const certPaths = trustedCertPaths(c.values, g.fields);
    trustedCertFields(g.fields).slice(0, certPaths.length).forEach((field, index) => {
      const e = entryFor({ ...field, key: `trustedCert${index + 1}` }, { [field.id]: certPaths[index] }, opts.secrets);
      if (e) entries.push(e);
    });
    if (g.id === 'appliance' && c.values.sshEnabled === true && c.values.sshKeyAccessEnabled === true) {
      const field = g.fields.find((f) => f.id === 'sshPublicKeys');
      if (field) {
        sshPublicKeys(c.values.sshPublicKeys, c.values.sshPublicKeyNames).forEach((key, index) => entries.push({
          key: `sshPublicKey${index + 1}`,
          jsonKey: false,
          value: key.path ?? key.fileName,
          field,
          secret: false
        }));
      }
    }
    if (g.target === 'snmp' && c.values.snmp_enabled === true) {
      const sys = get('General', 'system');
      sys.entries.push({
        key: 'snmpEnabled',
        jsonKey: 'snmpEnabled',
        value: true,
        field: { id: 'snmpEnabled', label: 'SNMP enabled', type: 'bool', key: 'snmpEnabled' },
        secret: false
      });
    }
    const originField = g.fields.find((field) => field.id === 'origin');
    const originDetails = originField && fieldAvailable(originField, c.version, c.platform, c.values)
      ? parseOriginHeaderDetails(c.values.origin)
      : [];
    if (originDetails.length > 0) {
      const synthetic: Field = { id: 'originHeaderDetailsList', label: 'Origin header details', type: 'text', key: 'originHeaderDetailsList' };
      entries.push({
        key: 'originHeaderDetailsList',
        jsonKey: 'originHeaderDetailsList',
        value: originDetails.map((_, i) => i + 1).join(','),
        field: synthetic,
        secret: false
      });
    }
    if (entries.length === 0 && originDetails.length === 0) continue;
    // 'General' holds both deploy-time and system keys; JSON only uses entries with a json key.
    get(g.iniSection, g.target === 'deploy' ? 'system' : g.target).entries.push(...entries);
    originDetails.forEach((detail, i) => {
      const f = (key: string): Field => ({ id: key, label: key, type: key === 'origin' ? 'text' : 'bool', key });
      get(`OriginHeaderDetails${i + 1}`, 'horizon', i + 1).entries.push(
        { key: 'origin', jsonKey: false, value: detail.origin, field: f('origin'), secret: false },
        { key: 'rewriteEnabled', jsonKey: false, value: detail.rewriteEnabled, field: f('rewriteEnabled'), secret: false },
        { key: 'autoGenerated', jsonKey: false, value: detail.autoGenerated, field: f('autoGenerated'), secret: false }
      );
    });
  }

  const outer = cascadeRole(c.values) === 'outer';
  if (outer) {
    const f = (key: string): Field => ({ id: key, label: key, type: 'text', key });
    const v = c.values;
    const wrp: Entry[] = [
      [ 'instanceId', CASCADE_INSTANCE_ID ],
      [ 'proxyDestinationUrl', String(v.cascade_innerUrl ?? '') ],
      [ 'proxyDestinationUrlThumbprints', String(v.cascade_innerThumbprints ?? '') ],
      [ 'proxyPattern', v.cascade_opswat === true ? CASCADE_PATTERN_OPSWAT : CASCADE_PATTERN ]
    ]
      .filter(([, val]) => val !== '')
      .map(([key, val]) => ({ key, jsonKey: key, value: val, field: f(key), secret: false }));
    const cascadeGroup = GROUPS.find((g) => g.id === 'cascade')!;
    trustedCertPaths(v, cascadeGroup.fields).forEach((path, index) => wrp.push({
      key: `trustedCert${index + 1}`,
      jsonKey: `trustedCert${index + 1}`,
      value: path,
      field: f(`trustedCert${index + 1}`),
      secret: false
    }));
    if (wrp.length) get('WebReverseProxy1', 'wrp', 1).entries.push(...wrp);
    const rules = forwardRules(v);
    if (rules) get('General', 'system').entries.push({ key: 'forwardrules', jsonKey: false, value: rules, field: f('forwardrules'), secret: false });
  }

  for (const l of LISTS) {
    const items = l.id === 'wrp' ? activeWrpItems(c) : c[l.id];
    const offset = outer && l.id === 'wrp' ? 1 : 0;
    items.forEach((item, i) => {
      const entries: Entry[] = [];
      for (const f of l.fields.filter((field) => field.trustedCertIndex === undefined && field.hostEntryIndex === undefined)) {
        if (!fieldAvailable(f, c.version, c.platform, item)) continue;
        const e = entryFor(f, item, opts.secrets);
        if (e) entries.push(e);
      }
      hostEntryValues(item, l.fields).forEach((value, index) => {
        const field = l.fields.find((candidate) => candidate.hostEntryIndex === 1)!;
        entries.push({ field, key: `hostEntry${index + 1}`, jsonKey: false, value, secret: false });
      });
      const certPaths = trustedCertPaths(item, l.fields);
      trustedCertFields(l.fields).slice(0, certPaths.length).forEach((field, index) => {
        const e = entryFor({ ...field, key: `trustedCert${index + 1}` }, { [field.id]: certPaths[index] }, opts.secrets);
        if (e) entries.push(e);
      });
      if (entries.length) get(l.iniSection(i + 1 + offset), l.target, i + 1 + offset).entries.push(...entries);
    });
  }

  return [...blocks.values()].sort((a, b) => sectionRank(a.section) - sectionRank(b.section) || a.section.localeCompare(b.section, 'en', { numeric: true }));
}

export function formatIniValue(v: Primitive): string {
  return typeof v === 'boolean' ? (v ? 'true' : 'false') : String(v);
}

export function generateIni(c: Config, opts: GenerateOptions = { secrets: 'placeholder' }): string {
  const blocks = collectBlocks(c, opts);
  const lines: string[] = [
    `# Generated by Gateway Forge for Omnissa Unified Access Gateway ${c.version}`,
    `# Deploy: ${deploymentCommand(c)}`,
    ''
  ];
  for (const b of blocks) {
    lines.push(`[${b.section}]`);
    const entries = b.section === 'Horizon'
      ? [...b.entries.filter((e) => e.key === 'authMethods' && e.value !== 'passthrough'), ...b.entries.filter((e) => e.key !== 'authMethods')]
      : b.entries;
    for (const e of entries) lines.push(`${e.key}=${formatIniValue(e.value)}`);
    lines.push('');
  }
  return lines.join('\n').replace(/\n+$/, '\n');
}

export function platformScript(c: Config): string {
  return platformDef(c.platform).script;
}

export function deploymentCommand(c: Config, switches = ''): string {
  const file = `.\\${iniFileName(c)}`;
  const script = `.\\${platformScript(c)}`;
  return `${script} -iniFile ${file}${switches}`;
}

export function iniFileName(c: Config): string {
  const n = String(c.values.name || c.values.uagName || 'uag').replace(/[^A-Za-z0-9._-]/g, '_');
  return `${n}.ini`;
}

export function jsonFileName(c: Config): string {
  return iniFileName(c).replace(/\.ini$/, '.json');
}

/** Settings JSON keys whose value is an array in the admin-UI export format. */
export const JSON_ARRAY_KEYS = new Set([
  'cipherSuites',
  'outboundCipherSuites',
  'tlsNamedGroups',
  'tlsSignatureSchemes',
  'additionalBlastExternalUrls',
  'additionalTunnelExternalUrls',
  'allowedAudiences',
  'blastAllowedHostHeaderValues'
]);

export function toJsonValue(key: string, value: Primitive): unknown {
  if (JSON_ARRAY_KEYS.has(key) && typeof value === 'string') {
    return value
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean);
  }
  return value;
}

function objectFrom(entries: Entry[]): Record<string, unknown> {
  const o: Record<string, unknown> = {};
  for (const e of entries) {
    if (e.jsonKey === false) continue;
    o[e.jsonKey] = toJsonValue(e.jsonKey, e.value);
  }
  return o;
}

/**
 * Settings document for the admin UI "Import settings" / PUT /rest/v1/config/settings.
 * The structure mirrors the admin-UI JSON export (systemSettings, edgeServiceSettingsList,
 * authMethodSettingsList, ...). Validate by importing into a non-production appliance first.
 */
export function generateJsonObject(c: Config, opts: GenerateOptions = { secrets: 'placeholder' }): Record<string, unknown> {
  const blocks = collectBlocks(c, opts);
  const doc: Record<string, unknown> = {};

  const system: Record<string, unknown> = {};
  for (const b of blocks.filter((x) => x.section === 'General')) Object.assign(system, objectFrom(b.entries));
  if (c.values.sshEnabled === true && c.values.sshKeyAccessEnabled === true) {
    const keys = sshPublicKeys(c.values.sshPublicKeys, c.values.sshPublicKeyNames)
      .filter((key) => key.data)
      .map(({ name, data }) => ({ name, data }));
    if (keys.length) system.sshPublicKeys = keys;
  }
  if (Object.keys(system).length) doc.systemSettings = system;

  const edge: Record<string, unknown>[] = [];
  for (const b of blocks) {
    if (b.target === 'horizon' && b.section === 'Horizon') {
      const view: Record<string, unknown> = { identifier: 'VIEW', enabled: true, ...objectFrom(b.entries) };
      const hostEntries = hostEntryValues(c.values, GROUPS.filter((g) => g.target === 'horizon').flatMap((g) => g.fields));
      if (hostEntries.length) view.hostEntries = hostEntries;
      if (c.values.origin && blocks.some((block) => block.section.startsWith('OriginHeaderDetails'))) {
        view.originHeaderDetailsList = parseOriginHeaderDetails(c.values.origin);
      }
      edge.push(view);
    }
    if (b.target === 'wrp') {
      const service: Record<string, unknown> = { identifier: 'WEB_REVERSE_PROXY', enabled: true, ...objectFrom(b.entries) };
      const hostEntries = b.entries
        .filter((entry) => entry.field.hostEntryIndex !== undefined)
        .sort((a, z) => a.field.hostEntryIndex! - z.field.hostEntryIndex!)
        .map((entry) => entry.value);
      if (hostEntries.length) service.hostEntries = hostEntries;
      edge.push(service);
    }
  }
  if (c.values.contentGateway_enabled === true) {
    const shared = c.values.contentGateway_mode === 'shared';
    const prefix = shared ? 'airwatch_' : 'contentGateway_';
    const service: Record<string, unknown> = {
      identifier: 'CONTENT_GATEWAY',
      enabled: true,
      airwatchComponentsInstalled: 'CG',
      proxyDestinationUrl: 'https://null',
      apiServerUrl: c.values[`${prefix}apiServerUrl`],
      apiServerUsername: c.values[`${prefix}apiServerUsername`],
      organizationGroupCode: c.values[`${prefix}organizationGroupCode`],
      airwatchServerHostname: c.values[`${prefix}airwatchServerHostname`],
      airwatchAgentStartUpMode: 'install'
    };
    const optional: [string, string][] = [
      ['cgConfigurationId', 'contentGateway_cgConfigId'],
      ['disableAutoConfigUpdate', `${prefix}disableAutoConfigUpdate`],
      ['airwatchOutboundProxy', `${prefix}airwatchOutboundProxy`],
      ['outboundProxyPort', `${prefix}outboundProxyPort`],
      ['outboundProxyHost', `${prefix}outboundProxyHost`],
      ['outboundProxyUsername', `${prefix}outboundProxyUsername`],
      ['reinitializeGatewayProcess', `${prefix}reinitializeGatewayProcess`]
    ];
    for (const [jsonKey, valueKey] of optional) {
      const value = c.values[valueKey];
      if (!isEmpty(value) && value !== false) service[jsonKey] = value;
    }
    const hostFields = GROUPS.find((group) => group.id === 'contentGateway')!.fields;
    if (shared) {
      const sharedFields = GROUPS.find((group) => group.id === 'airwatch')!.fields;
      const hostEntries = hostEntryValues(c.values, sharedFields);
      if (hostEntries.length) service.hostEntries = hostEntries;
    } else {
      const hostEntries = hostEntryValues(c.values, hostFields);
      if (hostEntries.length) service.hostEntries = hostEntries;
    }
    edge.push(service);
  }
  if (edge.length) doc.edgeServiceSettingsList = { edgeServiceSettingsList: edge };

  const radius = blocks.find((b) => b.target === 'radius');
  if (radius) doc.authMethodSettingsList = { authMethodSettingsList: [{ name: 'radius-auth', enabled: true, ...objectFrom(radius.entries) }] };

  const saml = blocks.find((b) => b.target === 'saml');
  if (saml) doc.idpExternalMetadataSettingsList = { idpExternalMetadataSettingsList: [objectFrom(saml.entries)] };

  const adminSaml = blocks.find((b) => b.target === 'adminSaml');
  if (adminSaml) doc.adminSAMLSettings = objectFrom(adminSaml.entries);

  const snmp = blocks.find((b) => b.target === 'snmp');
  if (snmp) doc.snmpSettings = objectFrom(snmp.entries);

  const syslog = blocks.filter((b) => b.target === 'syslog').map((b) => objectFrom(b.entries));
  if (syslog.length) doc.syslogSettings = { syslogServerSettingsList: syslog };

  return doc;
}

export function generateJson(c: Config, opts: GenerateOptions = { secrets: 'placeholder' }): string {
  return JSON.stringify(generateJsonObject(c, opts), null, 2) + '\n';
}

export function manifestFileName(c: Config): string {
  const base = String(c.values.ocp_volume || 'uag-bootable-volume').replace(/[^a-z0-9.-]/gi, '-');
  return `${base}.${c.values.ocp_volumeSourceMode === 'console' ? 'md' : 'yaml'}`;
}

/** CDI DataVolume + DataSource manifest used as the OpenShift bootable-volume preparation artifact. */
export function generateBootableVolumeManifest(c: Config): string {
  if (c.platform !== 'openshift') return '# OpenShift bootable-volume manifest: select the OpenShift platform first.\n';
  const v = c.values;
  if (v.ocp_volumeSourceMode === 'console') {
    return [
      '# OpenShift bootable-volume preparation runbook',
      '',
      'Gateway Forge cannot upload a local QCOW2 file to an OpenShift cluster, so this mode intentionally emits no Kubernetes manifest.',
      '',
      `1. In the OpenShift web console, select the **${v.ocp_namespace || '<destination-project>'}** project.`,
      '2. Open Virtualization > Bootable volumes and start the local image upload flow.',
      `3. Use **${v.ocp_volume || '<volume-name>'}** as the volume name and select storage class **${v.ocp_storageClass || '<storage-class>'}**.`,
      `4. Allocate at least **${v.ocp_diskSizeGi || 20} GiB** and complete the upload.`,
      `5. Verify the DataVolume/PVC/DataSource named **${v.ocp_volume || '<volume-name>'}** report the expected Succeeded/Bound state.`,
      '6. Continue with the generated OpenShift deployment PowerShell command.',
      '',
      'The namespace, StorageClass, NADs, RBAC, NetworkPolicies and cluster capacity must already exist.',
      ''
    ].join('\n');
  }
  const q = (x: unknown) => JSON.stringify(String(x ?? ''));
  const volume = String(v.ocp_volume || '<volume-name>');
  const namespace = String(v.ocp_namespace || '<destination-project>');
  const disk = Number(v.ocp_diskSizeGi) || 20;
  return [
    'apiVersion: cdi.kubevirt.io/v1beta1',
    'kind: DataVolume',
    'metadata:',
    `  name: ${q(volume)}`,
    `  namespace: ${q(namespace)}`,
    '  annotations:',
    `    description: "UAG bootable volume generated by Gateway Forge"`,
    'spec:',
    '  source:',
    '    http:',
    `      url: ${q(v.ocp_qcow2Url || '<cluster-reachable-qcow2-url>')}`,
    '  storage:',
    '    accessModes:',
    '      - ReadWriteMany',
    '    volumeMode: Filesystem',
    '    resources:',
    '      requests:',
    `        storage: "${disk}Gi"`,
    `    storageClassName: ${q(v.ocp_storageClass || '<rwx-storage-class>')}`,
    '---',
    'apiVersion: cdi.kubevirt.io/v1beta1',
    'kind: DataSource',
    'metadata:',
    `  name: ${q(volume)}`,
    `  namespace: ${q(namespace)}`,
    '  labels:',
    '    instancetype.kubevirt.io/default-preference: linux',
    '  annotations:',
    '    vm.kubevirt.io/os: "linux"',
    '    description: "UAG bootable volume generated by Gateway Forge"',
    'spec:',
    '  source:',
    '    pvc:',
    `      name: ${q(volume)}`,
    `      namespace: ${q(namespace)}`,
    ''
  ].join('\n');
}
